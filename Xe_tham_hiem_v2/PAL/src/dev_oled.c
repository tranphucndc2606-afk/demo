static void I2C_Start(void) { I2C1->CR1 |= I2C_CR1_START; while (!(I2C1->SR1 & I2C_SR1_SB)); }
static void I2C_Write(uint8_t data) { I2C1->DR = data; while (!(I2C1->SR1 & I2C_SR1_TXE)); }
static void I2C_Stop(void) { I2C1->CR1 |= I2C_CR1_STOP; }

static void OLED_SendCmd(uint8_t cmd) {
    I2C_Start(); I2C_Write(OLED_ADDR); (void)I2C1->SR2;
    I2C_Write(0x00); I2C_Write(cmd); I2C_Stop();
}

void Dev_OLED_Init(void) {
    RCC->AHB1ENR |= RCC_AHB1ENR_GPIOBEN;
    RCC->APB1ENR |= RCC_APB1ENR_I2C1EN;

    // Cấu hình I2C1 (PB6: SCL, PB7: SDA) Mode Alternate Function Open-Drain
    GPIOB->MODER |= (2 << (6 * 2)) | (2 << (7 * 2));
    GPIOB->OTYPER |= (1 << 6) | (1 << 7);
    GPIOB->PUPDR |= (1 << (6 * 2)) | (1 << (7 * 2));
    GPIOB->AFR[0] |= (4 << (6 * 4)) | (4 << (7 * 4));

    I2C1->CR1 |= I2C_CR1_SWRST;
    for(volatile int i = 0; i < 100; i++);
    I2C1->CR1 &= ~I2C_CR1_SWRST;
    I2C1->CR2 = 16; I2C1->CCR = 160; I2C1->TRISE = 17; I2C1->CR1 |= I2C_CR1_PE;

    Delay_ms(100);
    OLED_SendCmd(0xAE); OLED_SendCmd(0x20); OLED_SendCmd(0x00);
    OLED_SendCmd(0x8D); OLED_SendCmd(0x14); OLED_SendCmd(0xAF);
    Delay_ms(100);
}

void Dev_OLED_Clear(void) {
    OLED_SendCmd(0xB0); OLED_SendCmd(0x00); OLED_SendCmd(0x10);
    I2C_Start(); I2C_Write(OLED_ADDR); (void)I2C1->SR2; I2C_Write(0x40);
    for (uint16_t i = 0; i < 1024; i++) I2C_Write(0x00);
    I2C_Stop();
}

static void OLED_SetCursor(uint8_t page, uint8_t col) {
    OLED_SendCmd(0xB0 + page);
    OLED_SendCmd(col & 0x0F);
    OLED_SendCmd(0x10 | ((col >> 4) & 0x0F));
}

static void OLED_PutChar(char c) {
    if (c < 32 || c > 90) c = 32;
    uint8_t idx = c - 32;
    I2C_Start(); I2C_Write(OLED_ADDR); (void)I2C1->SR2; I2C_Write(0x40);
    for (uint8_t i = 0; i < 8; i++) I2C_Write(Font8x8[idx][i]);
    I2C_Stop();
}

void Dev_OLED_PrintString(uint8_t page, uint8_t col, const char* str) {
    OLED_SetCursor(page, col);
    while(*str) {
        if (*str >= 'a' && *str <= 'z') OLED_PutChar(*str - 32);
        else OLED_PutChar(*str);
        str++;
    }
}
